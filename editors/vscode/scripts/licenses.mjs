import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

async function packageForInput(input, root) {
  const absolute = path.resolve(root, input);
  if (!absolute.split(path.sep).includes("node_modules")) return null;
  let directory = path.dirname(absolute);
  while (directory !== path.dirname(directory)) {
    try {
      const metadata = JSON.parse(await readFile(path.join(directory, "package.json"), "utf8"));
      if (!metadata.name || !metadata.version) throw new Error(`Missing package name or version: ${directory}`);
      return { directory, metadata };
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    directory = path.dirname(directory);
  }
  throw new Error(`No installed package metadata for bundled input: ${input}`);
}

async function licenseFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const selected = entries.filter(entry => /^(licen[cs]e|copying|notice|patents)(?:[.-].*)?$/i.test(entry.name));
  if (!selected.some(entry => /^(licen[cs]e|copying)(?:[.-].*)?$/i.test(entry.name))) {
    throw new Error(`Missing license in installed bundled package: ${directory}`);
  }
  selected.sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  return Promise.all(selected.map(async entry => {
    if (!entry.isFile()) throw new Error(`License is not a regular file: ${path.join(directory, entry.name)}`);
    const data = await readFile(path.join(directory, entry.name));
    if (!data.toString("utf8").trim() || !Buffer.from(data.toString("utf8")).equals(data)) {
      throw new Error(`License is empty or not UTF-8 text: ${path.join(directory, entry.name)}`);
    }
    return { name: entry.name, data };
  }));
}

// Only packages that contribute bytes to esbuild's output require these notices.
// Source license files are retained verbatim, including copyright attribution.
export async function generateNotices(metafile, root = process.cwd()) {
  const inputs = new Set();
  for (const output of Object.values(metafile.outputs)) {
    for (const [input, contribution] of Object.entries(output.inputs)) {
      if (contribution.bytesInOutput > 0) inputs.add(input);
    }
  }
  const packages = new Map();
  for (const input of [...inputs].sort()) {
    const pkg = await packageForInput(input, root);
    if (pkg) packages.set(pkg.directory, pkg);
  }
  const ordered = [...packages.values()].sort((a, b) => {
    const left = `${a.metadata.name} ${a.metadata.version}`;
    const right = `${b.metadata.name} ${b.metadata.version}`;
    return left < right ? -1 : left > right ? 1 : 0;
  });
  const chunks = [Buffer.from("Doggo VS Code extension third-party notices\n\nGenerated by esbuild.config.mjs from packages contributing bytes to the actual\nesbuild output. License files below are copied verbatim from installed packages;\nno registry provenance is inferred. Run npm run bundle after dependency changes.\n")];
  for (const { directory, metadata } of ordered) {
    chunks.push(Buffer.from(`\n========================================================================\nComponent: ${metadata.name} ${metadata.version}\n`));
    for (const field of ["author", "contributors"]) {
      if (metadata[field]) chunks.push(Buffer.from(`${field}: ${typeof metadata[field] === "string" ? metadata[field] : JSON.stringify(metadata[field])}\n`));
    }
    for (const file of await licenseFiles(directory)) {
      chunks.push(Buffer.from(`\n--- ${file.name} ---\n`), file.data);
      if (file.data.at(-1) !== 10) chunks.push(Buffer.from("\n"));
    }
  }
  return Buffer.concat(chunks);
}

export async function writeNotices(metafile, { root = process.cwd(), check = false } = {}) {
  const generated = await generateNotices(metafile, root);
  const destination = path.join(root, "THIRD_PARTY_NOTICES");
  if (!check) {
    await writeFile(destination, generated);
    return;
  }
  const current = await readFile(destination);
  if (!current.equals(generated)) {
    throw new Error("THIRD_PARTY_NOTICES is stale; run npm run bundle");
  }
}
