type importSet struct {
	byPath     map[string]ImportInfo
	pathByName map[string]string
	fixed      map[string]struct{}
}

func newInteropImportSet() *importSet {
	imports := &importSet{
		byPath:     map[string]ImportInfo{"reflect": {Alias: "reflect", Path: "reflect"}},
		pathByName: map[string]string{"reflect": "reflect"},
		fixed:      map[string]struct{}{"reflect": {}},
	}
	for _, name := range types.Universe.Names() {
		imports.reserve(name)
	}
	for _, name := range []string{"RegisterPackage", "init"} {
		imports.reserve(name)
	}
	return imports
}

func newImportSet() *importSet {
	imports := &importSet{
		byPath:     make(map[string]ImportInfo),
		pathByName: make(map[string]string),
		fixed:      make(map[string]struct{}),
	}
	for _, fixed := range []ImportInfo{
		{Alias: "context", Path: "context"},
		{Alias: "fmt", Path: "fmt"},
		{Alias: "os", Path: "os"},
		{Alias: "reflect", Path: "reflect"},
		{Alias: "interop", Path: "doggo/internal/interop"},
		{Alias: "types", Path: "doggo/internal/types"},
		{Alias: "atom", Path: "doggo/internal/types/atom"},
	} {
		imports.byPath[fixed.Path] = fixed
		imports.pathByName[fixed.Alias] = fixed.Path
		imports.fixed[fixed.Path] = struct{}{}
	}
	for _, name := range types.Universe.Names() {
		imports.reserve(name)
	}
	for _, name := range []string{
		"CallbackInvoker", "callbackContextProvider", "callbackCallContext",
		"zeroValue", "wrapGoValue", "unwrapResult", "unwrapToError",
	} {
		imports.reserve(name)
	}
	return imports
}

func (s *importSet) reserve(name string) {
	if _, exists := s.pathByName[name]; !exists {
		s.pathByName[name] = ""
	}
}

func (s *importSet) allocate(preferredName string) string {
	name := preferredName
	for suffix := 2; ; suffix++ {
		if _, used := s.pathByName[name]; !used {
			s.pathByName[name] = ""
			return name
		}
		name = fmt.Sprintf("%s%d", preferredName, suffix)
	}
}

func (s *importSet) add(path, preferredName string) string {
	if existing, ok := s.byPath[path]; ok {
		return existing.Alias
	}

	alias := preferredName
	for suffix := 2; ; suffix++ {
		if _, used := s.pathByName[alias]; !used {
			break
		}
		alias = fmt.Sprintf("%s%d", preferredName, suffix)
	}
	info := ImportInfo{Alias: alias, Path: path}
	s.byPath[path] = info
	s.pathByName[alias] = path
	return alias
}

func (s *importSet) addPackage(pkg *types.Package) string {
	if pkg == nil || pkg.Path() == "" || pkg.Path() == "builtin" {
		return ""
	}
	return s.add(pkg.Path(), pkg.Name())
}

func (s *importSet) qualifier(pkg *types.Package) string {
	return s.addPackage(pkg)
}

func (s *importSet) imports() []ImportInfo {
	imports := make([]ImportInfo, 0, len(s.byPath)-len(s.fixed))
	for path, info := range s.byPath {
		if _, fixed := s.fixed[path]; !fixed {
			imports = append(imports, info)
		}
	}
	sort.Slice(imports, func(i, j int) bool {
		return imports[i].Path < imports[j].Path
	})
	return imports
}

