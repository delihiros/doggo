// wrapGoValue はGo値をDoggo値に変換します。
func wrapGoValue(v interface{}) (types.Value, error) {
	if val, ok := v.(types.Value); ok {
		return val, nil
	}
	val, err := interop.ConvertReflectValueToDoggo(reflect.ValueOf(v))
	if err != nil {
		return nil, fmt.Errorf("reify argument conversion failed: %w", err)
	}
	return val, nil
}

func unwrapResult[T any](v types.Value) T {
	var zero T
	if v == nil || v == atom.NilValue {
		return zero
	}
	if goObj, ok := v.(*atom.GoObject); ok {
		if typed, ok := goObj.Unwrap().(T); ok {
			return typed
		}
	}
	if typed, ok := v.(T); ok {
		return typed
	}
	targetType := reflect.TypeOf((*T)(nil)).Elem()
	converted, err := interop.ConvertDoggoToReflectValue(v, targetType)
	if err != nil || !converted.IsValid() {
		return zero
	}
	if typed, ok := converted.Interface().(T); ok {
		return typed
	}
	return zero
}

// unwrapToError はDoggo値をerrorに変換します。
func unwrapToError(v types.Value) error {
	if v == nil || v == atom.NilValue {
		return nil
	}
	if err, ok := v.(error); ok {
		return err
	}
	if goObj, ok := v.(*atom.GoObject); ok {
		if err, ok := goObj.Unwrap().(error); ok {
			return err
		}
	}
	return nil
}

