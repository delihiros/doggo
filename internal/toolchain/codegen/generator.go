func isSupportedInteropType(typeName *types.TypeName) bool {
	switch t := typeName.Type().(type) {
	case *types.Alias:
		if t.TypeParams().Len() > 0 {
			return false
		}
	case *types.Named:
		if t.TypeParams().Len() > 0 {
			return false
		}
	}

	if iface, ok := typeName.Type().Underlying().(*types.Interface); ok {
		iface.Complete()
		return iface.IsMethodSet()
	}
	return true
}

// Constants assigned to interface{} use their default Go type. A valid native
// constant may exceed that type, even though it can be used in other contexts.
func isSupportedInteropConstant(value *types.Const, sizes types.Sizes) bool {
	basic, ok := value.Type().Underlying().(*types.Basic)
	if !ok || basic.Info()&types.IsUntyped == 0 {
		return true
	}
	switch basic.Kind() {
	case types.UntypedInt, types.UntypedRune:
		bits := int64(32) // The default type of an untyped rune is always int32.
		if basic.Kind() == types.UntypedInt {
			bits = sizes.Sizeof(types.Typ[types.Int]) * 8
		}
		limit := constant.Shift(constant.MakeInt64(1), token.SHL, uint(bits-1))
		return constant.Compare(value.Val(), token.GEQ, constant.UnaryOp(token.SUB, limit, 0)) &&
			constant.Compare(value.Val(), token.LSS, limit)
	case types.UntypedFloat:
		// Inexact finite rounding is valid when defaulting to float64.
		rounded, _ := constant.Float64Val(value.Val())
		return !math.IsInf(rounded, 0)
	case types.UntypedComplex:
		realPart, _ := constant.Float64Val(constant.Real(value.Val()))
		imagPart, _ := constant.Float64Val(constant.Imag(value.Val()))
		return !math.IsInf(realPart, 0) && !math.IsInf(imagPart, 0)
	}
	return true
}

func generateInteropFile(projectRoot, output string, targetPkgs []string) error {
	output, outputRel, err := containedOutput(projectRoot, output)
	if err != nil {
		return fmt.Errorf("invalid output path: %w", err)
	}
	root, absolute, err := project.OpenVerifiedRoot(projectRoot)
	if err != nil {
		return err
	}
	defer root.Close()
	if err := generateInteropFileRoot(root, absolute, output, outputRel, targetPkgs, false); err != nil {
		return err
	}
	fmt.Printf("Generated %s for packages: %v\n", output, targetPkgs)
	return nil
}

func generateInteropFileRoot(root *os.Root, projectRoot, output, outputRel string, targetPkgs []string, isolated bool) error {
	if err := project.VerifyRootPath(projectRoot, root); err != nil {
		return err
	}
	goModPath := filepath.Join(projectRoot, "go.mod")
	env := os.Environ()
	gomodEnv := fmt.Sprintf("GOMOD=%s", goModPath)
	filteredEnv := make([]string, 0, len(env)+2)
	for _, e := range env {
		if strings.HasPrefix(e, "GOMOD=") || isolated && strings.HasPrefix(e, "GOWORK=") {
			continue
		}
		filteredEnv = append(filteredEnv, e)
	}
	filteredEnv = append(filteredEnv, gomodEnv)
	if isolated {
		filteredEnv = append(filteredEnv, "GOWORK=off")
	}
	loadDir, err := packageLoadDir(projectRoot, filteredEnv)
	if err != nil {
		return err
	}

	cfg := &packages.Config{
		Mode:       packages.NeedName | packages.NeedTypes | packages.NeedTypesSizes,
		Dir:        loadDir,
		Env:        filteredEnv,
		Tests:      false,
		BuildFlags: moduleBuildFlags(isolated),
	}

	if len(targetPkgs) == 0 {
		return fmt.Errorf("no packages loaded")
	}
	// One load shares dependency export data across all target packages instead
	// of repeating go list and parsing their common dependencies for each target.
	pkgs, err := packages.Load(cfg, targetPkgs...)
	if err != nil {
		return fmt.Errorf("load packages %q: %w", targetPkgs, err)
	}
	if len(pkgs) == 0 {
		return fmt.Errorf("load packages %q: no packages returned", targetPkgs)
	}
	for _, pkg := range pkgs {
		if len(pkg.Errors) > 0 {
			return fmt.Errorf("load package %q: %v", pkg.PkgPath, pkg.Errors)
		}
		if pkg.IllTyped {
			return fmt.Errorf("load package %q: package or dependency is ill-typed", pkg.PkgPath)
		}
	}

	// Allocate aliases in path order so query order cannot change the registry.
	sort.Slice(pkgs, func(i, j int) bool { return pkgs[i].PkgPath < pkgs[j].PkgPath })
	imports := newInteropImportSet()
	seen := make(map[string]bool, len(pkgs))
	var data []PkgData
	for _, pkg := range pkgs {
		if seen[pkg.PkgPath] {
			continue
		}
		seen[pkg.PkgPath] = true
		alias := imports.add(pkg.PkgPath, pkg.Name)
		pData := PkgData{
			Name:    alias,
			PkgPath: pkg.PkgPath,
		}

		scope := pkg.Types.Scope()
		for _, name := range scope.Names() {
			obj := scope.Lookup(name)
			if obj == nil || !obj.Exported() {
				continue
			}

			if typeName, ok := obj.(*types.TypeName); ok {
				if !isSupportedInteropType(typeName) {
					continue
				}
				underlying := typeName.Type().Underlying()
				switch underlying.(type) {
				case *types.Struct, *types.Interface:
					pData.Exports = append(pData.Exports, ExportData{
						Name:    name,
						PkgName: alias,
						IsType:  true,
					})
				case *types.Basic:
					if typeName.Type() != underlying {
						if pkg.PkgPath == "reflect" && (name == "Kind" || name == "ChanDir") {
							continue
						}
						pData.Exports = append(pData.Exports, ExportData{
							Name:    name,
							PkgName: alias,
							IsType:  true,
						})
					}
				}
				continue
			}

			switch v := obj.(type) {
			case *types.Func:
				sig := v.Type().(*types.Signature)
				if sig.TypeParams() != nil && sig.TypeParams().Len() > 0 {
					continue
				}
				pData.Exports = append(pData.Exports, ExportData{
					Name:    name,
					PkgName: alias,
					IsType:  false,
				})
			case *types.Var:
				pData.Exports = append(pData.Exports, ExportData{
					Name:    name,
					PkgName: alias,
					IsType:  false,
				})
			case *types.Const:
				if !isSupportedInteropConstant(v, pkg.TypesSizes) {
					continue
				}
				pData.Exports = append(pData.Exports, ExportData{
					Name:    name,
					PkgName: alias,
					IsType:  false,
				})
			}
		}
		data = append(data, pData)
	}

	t, err := template.New("gen").Parse(interopTemplate)
	if err != nil {
		return err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, map[string]interface{}{"Pkgs": data}); err != nil {
		return err
	}
	formatted, err := formatGoSource(buf.Bytes())
	if err != nil {
		return err
	}
	if err := validateGeneratedPackage(projectRoot, output, formatted, isolated); err != nil {
		return fmt.Errorf("generated interop package does not compile: %w", err)
	}
	if err := project.VerifyRootPath(projectRoot, root); err != nil {
		return err
	}
	if err := writeGeneratedFileRoot(root, outputRel, formatted); err != nil {
		return err
	}
	if err := project.VerifyRootPath(projectRoot, root); err != nil {
		return err
	}

	return nil
}

func collectTypeImports(t types.Type, imports *importSet) {
	switch tt := t.(type) {
	case *types.Named:
		imports.addPackage(tt.Obj().Pkg())
		for i := 0; i < tt.TypeArgs().Len(); i++ {
			collectTypeImports(tt.TypeArgs().At(i), imports)
		}
	case *types.Alias:
		imports.addPackage(tt.Obj().Pkg())
		for i := 0; i < tt.TypeArgs().Len(); i++ {
			collectTypeImports(tt.TypeArgs().At(i), imports)
		}
	case *types.Pointer:
		collectTypeImports(tt.Elem(), imports)
	case *types.Slice:
		collectTypeImports(tt.Elem(), imports)
	case *types.Array:
		collectTypeImports(tt.Elem(), imports)
	case *types.Map:
		collectTypeImports(tt.Key(), imports)
		collectTypeImports(tt.Elem(), imports)
	case *types.Chan:
		collectTypeImports(tt.Elem(), imports)
	case *types.Signature:
		collectTypeImports(tt.Params(), imports)
		collectTypeImports(tt.Results(), imports)
	case *types.Tuple:
		for i := 0; i < tt.Len(); i++ {
			collectTypeImports(tt.At(i).Type(), imports)
		}
	case *types.Struct:
		for i := 0; i < tt.NumFields(); i++ {
			collectTypeImports(tt.Field(i).Type(), imports)
		}
	case *types.Interface:
		for i := 0; i < tt.NumMethods(); i++ {
			collectTypeImports(tt.Method(i).Type(), imports)
		}
		for i := 0; i < tt.NumEmbeddeds(); i++ {
			collectTypeImports(tt.EmbeddedType(i), imports)
		}
	case *types.Union:
		for i := 0; i < tt.Len(); i++ {
			collectTypeImports(tt.Term(i).Type(), imports)
		}
	}
}

func parseInterface(ifaceType *types.Interface, pkgPath, pkgAlias, ifaceName string, imports *importSet) InterfaceImplData {
	structName := imports.allocate(generateStructName(pkgAlias, ifaceName))
	imports.reserve("New" + structName)
	implementation := InterfaceImplData{
		StructName:    structName,
		InterfaceName: ifaceName,
		PkgPath:       pkgPath,
		PkgAlias:      pkgAlias,
		TypeVar:       imports.allocate(lowerFirst(ifaceName) + "Type"),
	}

	for i := 0; i < ifaceType.NumMethods(); i++ {
		method := ifaceType.Method(i)
		sig := method.Type().(*types.Signature)

		bm := InterfaceMethod{
			Name: method.Name(),
		}

		params := sig.Params()
		for j := 0; j < params.Len(); j++ {
			param := params.At(j)
			collectTypeImports(param.Type(), imports)
			paramType := param.Type()
			variadic := sig.Variadic() && j == params.Len()-1
			if variadic {
				paramType = paramType.(*types.Slice).Elem()
			}
			paramName := fmt.Sprintf("arg%d", j)
			paramTypeString := types.TypeString(paramType, imports.qualifier)
			value := paramName
			if variadic {
				value = "[]" + paramTypeString + "(" + paramName + ")"
			}
			bm.Params = append(bm.Params, ParamInfo{
				Name:     paramName,
				Type:     paramTypeString,
				Value:    value,
				Variadic: variadic,
			})
		}

		results := sig.Results()
		for j := 0; j < results.Len(); j++ {
			result := results.At(j)
			collectTypeImports(result.Type(), imports)
			resultType := types.TypeString(result.Type(), imports.qualifier)
			bm.Results = append(bm.Results, ResultInfo{
				Type: resultType,
			})
			if resultType == "error" {
				bm.HasError = true
			}
		}

		implementation.Methods = append(implementation.Methods, bm)
	}

	return implementation
}

func generateStructName(pkgAlias, ifaceName string) string {
	return upperFirst(pkgAlias) + ifaceName + "Impl"
}

func upperFirst(value string) string {
	if value == "" {
		return ""
	}
	r, size := utf8.DecodeRuneInString(value)
	return string(unicode.ToUpper(r)) + value[size:]
}

func lowerFirst(value string) string {
	if value == "" {
		return ""
	}
	r, size := utf8.DecodeRuneInString(value)
	return string(unicode.ToLower(r)) + value[size:]
}

func toLower(s string) string {
	return strings.ToLower(s)
}

func RunReifyGenCLI(args []string) error {
	fs := flag.NewFlagSet("reify_gen", flag.ContinueOnError)
	var output string
	fs.StringVar(&output, "o", "generated_reify.go", "output file path")
	if err := fs.Parse(args); err != nil {
		return err
	}

	projectRoot, err := findProjectRoot()
	if err != nil {
		return fmt.Errorf("failed to find project root: %w", err)
	}

	if !filepath.IsAbs(output) {
		output, err = filepath.Abs(output)
		if err != nil {
			return fmt.Errorf("resolve output path: %w", err)
		}
	}
	candidates := make([]reifytarget.Candidate, len(fs.Args()))
	for i, source := range fs.Args() {
		candidates[i] = reifytarget.Candidate{Source: source, Required: true}
	}
	_, err = GenerateReifyFile(projectRoot, output, candidates)
	return err
}

func GenerateReifyFile(moduleRoot, output string, candidates []reifytarget.Candidate) ([]project.ReifyTarget, error) {
	return generateReifyFile(moduleRoot, output, candidates)
}

type resolvedReifyCandidate struct {
	resolved reifytarget.Resolved
	pkg      *packages.Package
	name     string
	source   string
	required bool
}

func generateReifyFile(moduleRoot, output string, candidates []reifytarget.Candidate) ([]project.ReifyTarget, error) {
	output, outputRel, err := containedOutput(moduleRoot, output)
	if err != nil {
		return nil, fmt.Errorf("invalid output path: %w", err)
	}
	root, absolute, err := project.OpenVerifiedRoot(moduleRoot)
	if err != nil {
		return nil, err
	}
	defer root.Close()
	targets, err := generateReifyFileRoot(root, absolute, output, outputRel, candidates, false)
	if err != nil {
		return nil, err
	}
	fmt.Printf("Generated %s with %d implementations\n", output, len(targets))
	return targets, nil
}

func generateReifyFileRoot(root *os.Root, moduleRoot, output, outputRel string, candidates []reifytarget.Candidate, isolated bool) ([]project.ReifyTarget, error) {
	if err := project.VerifyRootPath(moduleRoot, root); err != nil {
		return nil, err
	}

	env := os.Environ()
	if isolated {
		filteredEnv := make([]string, 0, len(env)+1)
		for _, e := range env {
			if !strings.HasPrefix(e, "GOWORK=") {
				filteredEnv = append(filteredEnv, e)
			}
		}
		env = append(filteredEnv, "GOWORK=off")
	}
	loadDir, err := packageLoadDir(moduleRoot, env)
	if err != nil {
		return nil, err
	}
	cfg := &packages.Config{
		Mode:       packages.NeedName | packages.NeedTypes | packages.NeedTypesSizes,
		Dir:        loadDir,
		Env:        env,
		Tests:      false,
		BuildFlags: moduleBuildFlags(isolated),
	}

	normalized := normalizeCandidates(candidates)
	var patterns []string
	for _, candidate := range normalized {
		lastDot := strings.LastIndex(candidate.Source, ".")
		if lastDot <= 0 || lastDot == len(candidate.Source)-1 {
			if candidate.Required {
				return nil, fmt.Errorf("reify target %q: invalid source (expected package.Interface)", candidate.Source)
			}
			continue
		}
		patterns = append(patterns, candidate.Source[:lastDot])
	}
	patterns = project.NormalizeStringSlice(patterns)
	byPackage := make(map[string][]*packages.Package, len(patterns))
	loadErrors := make(map[string]error)
	if len(patterns) > 0 {
		loaded, loadErr := packages.Load(cfg, patterns...)
		if loadErr == nil {
			for _, pkg := range loaded {
				byPackage[pkg.PkgPath] = append(byPackage[pkg.PkgPath], pkg)
			}
		} else {
			// A driver-level error may concern only an optional package. Preserve
			// per-package required/optional behavior on this exceptional path.
			for _, pattern := range patterns {
				byPackage[pattern], loadErrors[pattern] = packages.Load(cfg, pattern)
			}
		}
	}
	for _, pattern := range patterns {
		if _, matched := byPackage[pattern]; !matched {
			// Relative and file patterns return a canonical PkgPath rather than
			// their query string. Retain the previous per-pattern lookup for those
			// exceptional queries instead of silently dropping optional targets.
			byPackage[pattern], loadErrors[pattern] = packages.Load(cfg, pattern)
		}
	}
	valid := make([]resolvedReifyCandidate, 0, len(normalized))
	for _, candidate := range normalized {
		spec := candidate.Source
		lastDot := strings.LastIndex(spec, ".")
		if lastDot <= 0 || lastDot == len(spec)-1 {
			if candidate.Required {
				return nil, fmt.Errorf("reify target %q: invalid source (expected package.Interface)", spec)
			}
			continue
		}
		pkgPath := spec[:lastDot]
		ifaceName := spec[lastDot+1:]

		pkgs, err := byPackage[pkgPath], loadErrors[pkgPath]
		if err != nil {
			if candidate.Required {
				return nil, fmt.Errorf("load package %q for interface %q: %w", pkgPath, spec, err)
			}
			continue
		}

		if len(pkgs) == 0 {
			if candidate.Required {
				return nil, fmt.Errorf("load package %q for interface %q: no packages returned", pkgPath, spec)
			}
			continue
		}
		loadErr := ""
		for _, loadedPkg := range pkgs {
			if len(loadedPkg.Errors) > 0 {
				loadErr = fmt.Sprint(loadedPkg.Errors)
				break
			}
			if loadedPkg.IllTyped {
				loadErr = "package or dependency is ill-typed"
				break
			}
		}
		if loadErr != "" {
			if candidate.Required {
				return nil, fmt.Errorf("load package %q for interface %q: %s", pkgPath, spec, loadErr)
			}
			continue
		}

		pkg := pkgs[0]
		target, err := reifytarget.Resolve(pkg.Types, ifaceName)
		if err != nil {
			if candidate.Required {
				return nil, fmt.Errorf("reify target %q: %w", spec, err)
			}
			continue
		}

		resolved := resolvedReifyCandidate{resolved: target, pkg: pkg, name: ifaceName, source: spec, required: candidate.Required}
		_, err = renderReifyFile([]resolvedReifyCandidate{resolved})
		if err != nil {
			if candidate.Required {
				return nil, fmt.Errorf("reify target %q: generated package does not compile: %w", spec, err)
			}
			continue
		}
		valid = append(valid, resolved)
	}

	selected, accepted := selectReifyCandidates(valid)
	formatted, err := renderReifyFile(selected)
	if err != nil {
		return nil, err
	}
	if validationErr := validateGeneratedPackage(moduleRoot, output, formatted, isolated); validationErr != nil || len(selected) != len(valid) {
		// Successful candidates share one semantic check. If the combined file
		// fails, retain the original individual filtering and required-target
		// diagnostics before checking the remaining combined file again. Aliases
		// also need individual checks so a public source cannot hide a forbidden
		// required source with the same runtime type.
		filtered := make([]resolvedReifyCandidate, 0, len(valid))
		for _, candidate := range valid {
			individual, candidateErr := renderReifyFile([]resolvedReifyCandidate{candidate})
			if candidateErr == nil {
				candidateErr = validateGeneratedPackage(moduleRoot, output, individual, isolated)
			}
			if candidateErr != nil {
				if candidate.required {
					return nil, fmt.Errorf("reify target %q: generated package does not compile: %w", candidate.source, candidateErr)
				}
				continue
			}
			filtered = append(filtered, candidate)
		}
		selected, accepted = selectReifyCandidates(filtered)
		formatted, err = renderReifyFile(selected)
		if err != nil {
			return nil, err
		}
		if err := validateGeneratedPackage(moduleRoot, output, formatted, isolated); err != nil {
			return nil, fmt.Errorf("combined generated reify package does not compile: %w", err)
		}
	}
	if err := project.VerifyRootPath(moduleRoot, root); err != nil {
		return nil, err
	}
	if err := writeGeneratedFileRoot(root, outputRel, formatted); err != nil {
		return nil, fmt.Errorf("failed to write output file: %w", err)
	}
	if err := project.VerifyRootPath(moduleRoot, root); err != nil {
		return nil, err
	}

	return accepted, nil
}

func selectReifyCandidates(valid []resolvedReifyCandidate) ([]resolvedReifyCandidate, []project.ReifyTarget) {
	byRuntime := make(map[string]resolvedReifyCandidate, len(valid))
	for _, candidate := range valid {
		if _, exists := byRuntime[candidate.resolved.Target.Runtime]; !exists {
			byRuntime[candidate.resolved.Target.Runtime] = candidate
		}
	}
	accepted := make([]project.ReifyTarget, 0, len(byRuntime))
	selected := make([]resolvedReifyCandidate, 0, len(byRuntime))
	for _, candidate := range byRuntime {
		accepted = append(accepted, candidate.resolved.Target)
		selected = append(selected, candidate)
	}
	accepted = project.NormalizeReifyTargets(accepted)
	sort.Slice(selected, func(i, j int) bool { return selected[i].resolved.Target.Source < selected[j].resolved.Target.Source })
	return selected, accepted
}

func renderReifyFile(candidates []resolvedReifyCandidate) ([]byte, error) {
	imports := newImportSet()
	implementations := make([]InterfaceImplData, 0, len(candidates))
	for _, candidate := range candidates {
		pkgAlias := imports.add(candidate.pkg.PkgPath, candidate.pkg.Name)
		implementations = append(implementations, parseInterface(
			candidate.resolved.Interface,
			candidate.pkg.PkgPath,
			pkgAlias,
			candidate.name,
			imports,
		))
	}
	data := TemplateData{Implementations: implementations, Imports: imports.imports()}

	tmpl, err := template.New("reify").Funcs(template.FuncMap{"toLower": toLower}).Parse(reifyTemplate)
	if err != nil {
		return nil, fmt.Errorf("failed to parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("failed to execute template: %w", err)
	}
	return formatGoSource(buf.Bytes())
}

func formatGoSource(source []byte) ([]byte, error) {
	formatted, err := format.Source(source)
	if err != nil {
		return nil, fmt.Errorf("failed to format generated Go: %w", err)
	}
	return formatted, nil
}

func normalizeCandidates(candidates []reifytarget.Candidate) []reifytarget.Candidate {
	required := make(map[string]bool, len(candidates))
	for _, candidate := range candidates {
		if candidate.Source == "" && !candidate.Required {
			continue
		}
		required[candidate.Source] = required[candidate.Source] || candidate.Required
	}
	out := make([]reifytarget.Candidate, 0, len(required))
	for source, isRequired := range required {
		out = append(out, reifytarget.Candidate{Source: source, Required: isRequired})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Source < out[j].Source })
	return out
}

func containedOutput(moduleRoot, output string) (string, string, error) {
	rootAbs, err := filepath.Abs(moduleRoot)
	if err != nil {
		return "", "", err
	}
	rootAbs, err = project.NormalizeSystemPath(rootAbs)
	if err != nil {
		return "", "", err
	}
	outputAbs, err := filepath.Abs(output)
	if err != nil {
		return "", "", err
	}
	outputAbs, err = project.NormalizeSystemPath(outputAbs)
	if err != nil {
		return "", "", err
	}
	if err := project.ValidateContainedPath(rootAbs, outputAbs); err != nil {
		return "", "", err
	}
	rel, err := filepath.Rel(rootAbs, outputAbs)
	if err != nil {
		return "", "", err
	}
	return outputAbs, rel, nil
}

func validateGeneratedPackage(moduleRoot, output string, source []byte, isolated bool) error {
	moduleRoot, err := project.NormalizeSystemPath(moduleRoot)
	if err != nil {
		return err
	}
	output, err = project.NormalizeSystemPath(output)
	if err != nil {
		return err
	}
	dirRel, err := filepath.Rel(moduleRoot, filepath.Dir(output))
	if err != nil {
		return err
	}
	pattern := "."
	if dirRel != "." {
		pattern = "./" + filepath.ToSlash(dirRel)
	}
	env := os.Environ()
	if isolated {
		filtered := make([]string, 0, len(env)+1)
		for _, value := range env {
			if !strings.HasPrefix(value, "GOWORK=") {
				filtered = append(filtered, value)
			}
		}
		env = append(filtered, "GOWORK=off")
	}
	loadDir, err := packageLoadDir(moduleRoot, env)
	if err != nil {
		return err
	}
	// The overlay must use the same spelling as Go's workspace module root.
	// Compiled file ownership is still compared using canonical paths below.
	loadOutput := filepath.Join(loadDir, dirRel, filepath.Base(output))
	pkgs, loadErr := packages.Load(&packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles |
			packages.NeedImports | packages.NeedDeps | packages.NeedTypes | packages.NeedTypesSizes,
		Dir:        loadDir,
		Env:        env,
		Tests:      false,
		BuildFlags: moduleBuildFlags(isolated),
		Overlay:    map[string][]byte{loadOutput: source},
	}, pattern)
	var diagnostics []string
	if loadErr != nil {
		diagnostics = append(diagnostics, loadErr.Error())
	}
	for _, pkg := range pkgs {
		for _, pkgErr := range pkg.Errors {
			diagnostics = append(diagnostics, pkgErr.Error())
		}
		if pkg.IllTyped && len(pkg.Errors) == 0 {
			diagnostics = append(diagnostics, pkg.PkgPath+": package or dependency is ill-typed")
		}
	}
	compiledPackages := 0
	for _, pkg := range pkgs {
		for _, file := range pkg.CompiledGoFiles {
			file, err := project.NormalizeSystemPath(filepath.Clean(file))
			if err != nil {
				return err
			}
			if file == output {
				compiledPackages++
				break
			}
		}
	}
	if compiledPackages != 1 {
		diagnostics = append(diagnostics, fmt.Sprintf("output %s belongs to %d compiled packages, want exactly one", output, compiledPackages))
	}
	if len(pkgs) == 0 && len(diagnostics) == 0 {
		diagnostics = append(diagnostics, "no packages returned")
	}
	if len(diagnostics) > 0 {
		return fmt.Errorf("%s", strings.Join(diagnostics, "; "))
	}
	return nil
}

func writeGeneratedFileRoot(root *os.Root, outputRel string, source []byte) error {
	return project.WriteFileAtomicRoot(root, outputRel, source, 0644)
}

func moduleBuildFlags(isolated bool) []string {
	if isolated {
		return []string{"-mod=mod"}
	}
	return nil
}
