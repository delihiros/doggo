// Package licenses generates redistribution notices from installed source dependencies
// and verifies that release archives contain the complete checked-in notices.
package licenses

import (
	"archive/tar"
	"archive/zip"
	"bytes"
	"compress/gzip"
	"debug/buildinfo"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime/debug"
	"sort"
	"strings"
	"unicode/utf8"
)

var releaseTargets = []string{"darwin/amd64", "darwin/arm64", "linux/amd64", "linux/arm64", "windows/amd64"}

type licenseFile struct {
	name string
	data []byte
}
type module struct {
	Path    string
	Version string
	Dir     string
	Main    bool
	Replace *module
}
type packageInfo struct {
	Module     *module
	Error      *struct{ Err string }
	DepsErrors []struct{ Err string }
}
type component struct {
	name    string
	version string
	source  string
	dir     string
	targets map[string]bool
}

// GenerateGo notices the dependency package graph of the CLI for every release
// target. It does not use go.mod's unlinked tool or test dependencies.
func GenerateGo(root string) ([]byte, error) {
	components := map[string]*component{}
	for _, target := range releaseTargets {
		parts := strings.Split(target, "/")
		output, err := runGo(root, []string{"GOOS=" + parts[0], "GOARCH=" + parts[1], "CGO_ENABLED=0"}, "list", "-deps", "-json", "./cmd/doggo")
		if err != nil {
			return nil, fmt.Errorf("resolve %s dependency packages: %w", target, err)
		}
		decoder := json.NewDecoder(bytes.NewReader(output))
		for {
			var pkg packageInfo
			if err := decoder.Decode(&pkg); errors.Is(err, io.EOF) {
				break
			} else if err != nil {
				return nil, err
			}
			if pkg.Error != nil {
				return nil, fmt.Errorf("resolve %s package: %s", target, pkg.Error.Err)
			}
			if len(pkg.DepsErrors) != 0 {
				return nil, fmt.Errorf("resolve %s dependency: %s", target, pkg.DepsErrors[0].Err)
			}
			m := pkg.Module
			if m == nil || m.Main {
				continue
			}
			key := m.Path + " " + m.Version
			c := components[key]
			if c == nil {
				source := m
				if m.Replace != nil {
					source = m.Replace
				}
				if source.Dir == "" {
					return nil, fmt.Errorf("module %s has no installed source directory", key)
				}
				c = &component{name: m.Path, version: m.Version, dir: source.Dir, targets: map[string]bool{}}
				if m.Replace != nil {
					c.source = strings.TrimSpace(m.Replace.Path + " " + m.Replace.Version)
				}
				components[key] = c
			}
			c.targets[target] = true
		}
	}
	goRoot, err := runGo(root, nil, "env", "GOROOT")
	if err != nil {
		return nil, err
	}
	goVersion, err := runGo(root, nil, "env", "GOVERSION")
	if err != nil {
		return nil, err
	}
	runtimeComponent := &component{name: "Go runtime", version: strings.TrimSpace(string(goVersion)), dir: strings.TrimSpace(string(goRoot)), targets: map[string]bool{}}
	for _, target := range releaseTargets {
		runtimeComponent.targets[target] = true
	}
	keys := make([]string, 0, len(components))
	for key := range components {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	ordered := []*component{runtimeComponent}
	for _, key := range keys {
		ordered = append(ordered, components[key])
	}
	var out bytes.Buffer
	out.WriteString("Doggo CLI third-party notices\n\nGenerated by go run ./cmd/license-notices from the CLI dependency package graphs\nfor CGO_ENABLED=0 release targets and the installed Go toolchain.\nRun the generator after dependency or toolchain changes. License files below are\ncopied verbatim from installed source packages; no registry provenance is inferred.\n")
	for _, c := range ordered {
		files, err := readLicenseFiles(c.dir)
		if err != nil {
			return nil, fmt.Errorf("%s %s: %w", c.name, c.version, err)
		}
		fmt.Fprintf(&out, "\n========================================================================\nComponent: %s %s\n", c.name, c.version)
		if c.source != "" {
			fmt.Fprintf(&out, "Source replacement: %s\n", c.source)
		}
		targets := make([]string, 0, len(c.targets))
		for target := range c.targets {
			targets = append(targets, target)
		}
		sort.Strings(targets)
		fmt.Fprintf(&out, "Targets: %s\n", strings.Join(targets, ", "))
		for _, file := range files {
			fmt.Fprintf(&out, "\n--- %s ---\n", file.name)
			out.Write(file.data)
			if !bytes.HasSuffix(file.data, []byte("\n")) {
				out.WriteByte('\n')
			}
		}
	}
	return out.Bytes(), nil
}

func runGo(root string, overrides []string, args ...string) ([]byte, error) {
	cmd := exec.Command("go", args...)
	cmd.Dir = root
	cmd.Env = os.Environ()
	for _, override := range overrides {
		name := strings.SplitN(override, "=", 2)[0]
		filtered := cmd.Env[:0]
		for _, value := range cmd.Env {
			if !strings.EqualFold(strings.SplitN(value, "=", 2)[0], name) {
				filtered = append(filtered, value)
			}
		}
		cmd.Env = append(filtered, override)
	}
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	output, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go %s: %w\n%s", strings.Join(args, " "), err, stderr.String())
	}
	return output, nil
}

func readLicenseFiles(dir string) ([]licenseFile, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []licenseFile
	foundLicense := false
	for _, entry := range entries {
		name := strings.ToUpper(entry.Name())
		base := strings.SplitN(name, ".", 2)[0]
		isLicense := base == "LICENSE" || base == "LICENCE" || base == "COPYING"
		if !isLicense && base != "NOTICE" && base != "PATENTS" {
			continue
		}
		if !entry.Type().IsRegular() {
			return nil, fmt.Errorf("license file %s is not a regular file", entry.Name())
		}
		data, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return nil, err
		}
		if len(bytes.TrimSpace(data)) == 0 || !utf8.Valid(data) {
			return nil, fmt.Errorf("license file %s is empty or not UTF-8 text", entry.Name())
		}
		files = append(files, licenseFile{name: entry.Name(), data: data})
		foundLicense = foundLicense || isLicense
	}
	if !foundLicense {
		return nil, fmt.Errorf("missing license in %s", dir)
	}
	sort.Slice(files, func(i, j int) bool { return files[i].name < files[j].name })
	return files, nil
}

// WriteGo updates the checked-in notices, or fails when check-only output differs.
func WriteGo(root string, check bool) error {
	data, err := GenerateGo(root)
	if err != nil {
		return err
	}
	path := filepath.Join(root, "THIRD_PARTY_NOTICES")
	if !check {
		return os.WriteFile(path, data, 0644)
	}
	existing, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !bytes.Equal(existing, data) {
		return errors.New("THIRD_PARTY_NOTICES is stale; run go run ./cmd/license-notices")
	}
	return nil
}

// VerifyArtifact checks the actual archive entries against the repository's
// complete license documents and checks CLI build metadata against the notices.
func VerifyArtifact(root, path string) error {
	entries, err := readArchive(path)
	if err != nil {
		return err
	}
	isVSIX := strings.HasSuffix(strings.ToLower(path), ".vsix")
	prefix, source := "", root
	if isVSIX {
		prefix, source = "extension/", filepath.Join(root, "editors", "vscode")
	}
	for _, name := range []string{"LICENSE", "THIRD_PARTY_NOTICES"} {
		archiveName := prefix + name
		// VSCE packages a source file named LICENSE as LICENSE.txt.
		if isVSIX && name == "LICENSE" {
			archiveName += ".txt"
		}
		got, ok := entries[archiveName]
		if !ok {
			return fmt.Errorf("%s: missing %s", path, archiveName)
		}
		want, err := os.ReadFile(filepath.Join(source, name))
		if err != nil {
			return err
		}
		if len(want) == 0 || !bytes.Equal(got, want) {
			return fmt.Errorf("%s: %s differs from complete repository document", path, archiveName)
		}
	}
	if isVSIX {
		bundle := entries["extension/dist/extension.js"]
		if len(bundle) == 0 {
			return fmt.Errorf("%s: missing extension/dist/extension.js", path)
		}
		current, err := os.ReadFile(filepath.Join(source, "dist", "extension.js"))
		if err != nil {
			return err
		}
		if !bytes.Equal(bundle, current) {
			return fmt.Errorf("%s: extension/dist/extension.js differs from the bundle used to generate notices", path)
		}
		return nil
	}
	binary := entries["doggo"]
	if len(binary) == 0 {
		binary = entries["doggo.exe"]
	}
	if len(binary) == 0 {
		return fmt.Errorf("%s: missing CLI binary", path)
	}
	info, err := buildinfo.Read(bytes.NewReader(binary))
	if err != nil {
		return fmt.Errorf("%s: read CLI build metadata: %w", path, err)
	}
	notices := entries["THIRD_PARTY_NOTICES"]
	for _, name := range append([]string{"Go runtime " + info.GoVersion}, moduleNames(info.Deps)...) {
		if !bytes.Contains(notices, []byte("Component: "+name+"\n")) {
			return fmt.Errorf("%s: THIRD_PARTY_NOTICES omits linked component %s", path, name)
		}
	}
	return nil
}

func moduleNames(modules []*debug.Module) []string {
	names := make([]string, 0, len(modules))
	for _, m := range modules {
		names = append(names, strings.TrimSpace(m.Path+" "+m.Version))
	}
	return names
}

const maxEntrySize = 256 << 20

func readArchive(path string) (map[string][]byte, error) {
	entries := map[string][]byte{}
	add := func(name string, reader io.Reader) error {
		if _, exists := entries[name]; exists {
			return fmt.Errorf("%s: duplicate archive entry %s", path, name)
		}
		data, err := io.ReadAll(io.LimitReader(reader, maxEntrySize+1))
		if err != nil {
			return err
		}
		if len(data) > maxEntrySize {
			return fmt.Errorf("%s: archive entry %s exceeds size limit", path, name)
		}
		entries[name] = data
		return nil
	}
	lower := strings.ToLower(path)
	if strings.HasSuffix(lower, ".zip") || strings.HasSuffix(lower, ".vsix") {
		archive, err := zip.OpenReader(path)
		if err != nil {
			return nil, err
		}
		defer archive.Close()
		for _, file := range archive.File {
			if !file.Mode().IsRegular() {
				continue
			}
			if file.UncompressedSize64 > maxEntrySize {
				return nil, fmt.Errorf("%s: archive entry %s exceeds size limit", path, file.Name)
			}
			reader, err := file.Open()
			if err != nil {
				return nil, err
			}
			err = errors.Join(add(file.Name, reader), reader.Close())
			if err != nil {
				return nil, err
			}
		}
		return entries, nil
	}
	if !strings.HasSuffix(lower, ".tar.gz") {
		return nil, fmt.Errorf("unsupported release archive: %s", path)
	}
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	compressed, err := gzip.NewReader(file)
	if err != nil {
		return nil, err
	}
	defer compressed.Close()
	archive := tar.NewReader(compressed)
	for {
		header, err := archive.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, err
		}
		if header.Typeflag != tar.TypeReg && header.Typeflag != tar.TypeRegA {
			continue
		}
		if header.Size > maxEntrySize {
			return nil, fmt.Errorf("%s: archive entry %s exceeds size limit", path, header.Name)
		}
		if err := add(header.Name, archive); err != nil {
			return nil, err
		}
	}
	return entries, nil
}
